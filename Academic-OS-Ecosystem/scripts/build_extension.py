"""
Build the Chrome extension (Manifest V3) from frontend/.

    python scripts/build_extension.py \
        --api-url https://your-api.example.com \
        --google-client-id 1234-abc.apps.googleusercontent.com

Output: extension/dist/ (load it via chrome://extensions > Load unpacked).

What the build guarantees:
* Only the files listed below are copied, and no backend code, .env files or
  credentials are included.
* The manifest CSP is 'script-src self', so every script must be a local file.
  The build fails if any HTML page still has an inline <script> or a remote
  <script src>. Chrome would block them at runtime.
* host_permissions covers only the API origin given with --api-url.
* The extension requests only the "identity" permission (for Google sign-in).
"""

import argparse
import json
import re
import shutil
import sys
import zipfile
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
FRONTEND = ROOT / "frontend"
EXTENSION = ROOT / "extension"
DIST = EXTENSION / "dist"

# Files that the hosted site has but the extension should not ship.
EXCLUDE_NAMES = {"index.backup.html", ".DS_Store"}
PAGES = ["index.html", "login.html", "404.html", "privacy-and-legal.html"]
EXTENSION_ID_RE = re.compile(r"^[a-p]{32}$")


def api_origin(api_url: str) -> str:
    parts = urlsplit(api_url)
    is_local = parts.scheme == "http" and parts.hostname in {"localhost", "127.0.0.1"}
    if parts.scheme != "https" and not is_local:
        raise SystemExit("--api-url must be https:// (http is only allowed for localhost).")
    if not parts.hostname or parts.path not in {"", "/"} or parts.query or parts.fragment:
        raise SystemExit("--api-url must be an origin only, e.g. https://api.example.com")
    return f"{parts.scheme}://{parts.netloc}"


def copy_frontend() -> None:
    if DIST.exists():
        shutil.rmtree(DIST)
    DIST.mkdir(parents=True)
    for src in FRONTEND.rglob("*"):
        if not src.is_file() or src.name in EXCLUDE_NAMES:
            continue
        rel = src.relative_to(FRONTEND)
        if rel.parts[0] in {"archive"}:
            continue
        dest = DIST / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)


def write_build_config(api_url: str, client_id: str) -> None:
    """Runtime config read before config.js. config.js keeps these values when set."""
    payload = {"API_URL": api_url, "GOOGLE_OAUTH_CLIENT_ID": client_id}
    (DIST / "build-config.js").write_text(
        "// Generated by scripts/build_extension.py. Public values only.\n"
        f"window.APP_CONFIG = Object.assign({{}}, window.APP_CONFIG, {json.dumps(payload)});\n",
        encoding="utf-8",
    )
    for page in PAGES:
        path = DIST / page
        if not path.exists():
            continue
        html = path.read_text(encoding="utf-8")
        html = html.replace('<script src="config.js"></script>',
                            '<script src="build-config.js"></script>\n<script src="config.js"></script>', 1)
        path.write_text(html, encoding="utf-8")


def write_manifest(origin: str) -> None:
    manifest = json.loads((EXTENSION / "manifest.template.json").read_text(encoding="utf-8"))
    manifest["host_permissions"] = [f"{origin}/*"]
    (DIST / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    shutil.copy2(EXTENSION / "background.js", DIST / "background.js")
    shutil.copytree(EXTENSION / "icons", DIST / "icons", dirs_exist_ok=True)


def check_csp() -> None:
    """Fail the build if any page would be blocked by the extension CSP."""
    problems = []
    inline = re.compile(r"<script(?![^>]*\bsrc=)[^>]*>", re.IGNORECASE)
    remote = re.compile(r"<script[^>]*\bsrc=[\"']https?:", re.IGNORECASE)
    handlers = re.compile(r"\son[a-z]+\s*=", re.IGNORECASE)
    for page in DIST.rglob("*.html"):
        text = page.read_text(encoding="utf-8")
        body = re.sub(r"<script[^>]*>.*?</script>", lambda m: m.group(0) if "src=" in m.group(0)[:200] else "<script>", text, flags=re.S)
        if inline.search(body):
            problems.append(f"{page.relative_to(DIST)}: inline <script> block")
        if remote.search(text):
            problems.append(f"{page.relative_to(DIST)}: remote <script src>")
        if handlers.search(text):
            problems.append(f"{page.relative_to(DIST)}: inline on* event handler attribute")
    for js in DIST.rglob("*.js"):
        if re.search(r"\beval\s*\(|new Function\s*\(", js.read_text(encoding="utf-8", errors="ignore")):
            problems.append(f"{js.relative_to(DIST)}: eval/new Function is not allowed by the CSP")
    if problems:
        raise SystemExit("CSP check failed:\n  " + "\n  ".join(problems))


def make_zip() -> Path:
    """Zip dist/ with files at the archive root, as the Chrome Web Store expects."""
    manifest = json.loads((DIST / "manifest.json").read_text(encoding="utf-8"))
    archive = EXTENSION / f"academic-os-extension-{manifest['version']}.zip"
    if archive.exists():
        archive.unlink()
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(DIST.rglob("*")):
            if path.is_file():
                zf.write(path, path.relative_to(DIST).as_posix())
    return archive


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--api-url", required=True, help="Backend origin, e.g. https://api.example.com")
    parser.add_argument("--google-client-id", required=True, help="Google OAuth client ID for the extension")
    parser.add_argument("--zip", action="store_true", help="Also write extension/academic-os-extension-<version>.zip")
    args = parser.parse_args()

    origin = api_origin(args.api_url)
    if not args.google_client_id.endswith(".apps.googleusercontent.com"):
        raise SystemExit("--google-client-id should end with .apps.googleusercontent.com")

    copy_frontend()
    write_build_config(origin, args.google_client_id)
    write_manifest(origin)
    check_csp()
    if args.zip:
        archive = make_zip()
        print(f"packaged {archive.relative_to(ROOT)} (manifest.json at the archive root)")
    print(f"built {DIST.relative_to(ROOT)} for API {origin}")
    print(f"Load this folder in chrome://extensions (it contains manifest.json): {DIST}")
    print("Next: add the extension ID to CHROME_EXTENSION_ORIGINS and FRONTEND_URL on the backend.")


if __name__ == "__main__":
    sys.exit(main())
